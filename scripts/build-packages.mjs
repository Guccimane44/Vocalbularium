import { spawnSync } from 'node:child_process';
import { cpSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';

// Every module's and facet's explanation (D13) is a markdown file beside its
// definition. The extension cannot read files at run time, so the texts are
// gathered into one generated module, keyed by their folder in the catalog,
// which the domain compiles with the rest.
const catalog = resolve('packages/domain/src/catalog');
const explanations = readdirSync(catalog, { recursive: true }).map(String).filter(path => path.endsWith('explanation.md')).sort()
  .map(path => [relative(catalog, resolve(catalog, path, '..')).split('\\').join('/'), readFileSync(resolve(catalog, path), 'utf8')]);
writeFileSync(resolve(catalog, 'explanations.generated.ts'), `// Generated by scripts/build-packages.mjs from each explanation.md; do not edit.
export const EXPLANATIONS: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(explanations), null, 2)};
`);

for (const project of ['packages/contracts/tsconfig.json', 'packages/domain/tsconfig.json']) {
  const result = spawnSync(process.execPath, [resolve('node_modules/typescript/bin/tsc'), '-p', project], { stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

// The catalog's prompt files and the composer's rules ship beside the compiled
// domain, where the composer reads them (D11).
cpSync(resolve('packages/domain/src'), resolve('packages/domain/dist'), { recursive: true, filter: source => !/\.ts$/.test(source) });
