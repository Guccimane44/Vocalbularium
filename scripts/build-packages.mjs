import { spawnSync } from 'node:child_process';
import { cpSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';

// Every family's, module's and facet's page (D20) has its text in `about.json`
// beside its definition, and every module its samples in `samples/`. The
// extension cannot read files at run time, so both are gathered into one
// generated module, keyed by their folder in the catalog, which the domain
// compiles with the rest.
const catalog = resolve('packages/domain/src/catalog');
const folderOf = path => relative(catalog, resolve(catalog, path, '..')).split('\\').join('/');
// English is `about.json`; each other interface language (D14) is
// `about.<language>.json` beside it. Samples are `samples/<language>.json`.
// A module's names in each other interface language, its own and its core's
// and facets', are `names.<language>.json` beside its definition (D25).
const about = {};
const samples = {};
const names = {};
for (const path of readdirSync(catalog, { recursive: true }).map(String).sort()) {
  const page = /(?:^|[\\/])about(?:\.([A-Za-z-]+))?\.json$/.exec(path);
  if (page) (about[folderOf(path)] ??= {})[page[1] ?? 'en'] = JSON.parse(readFileSync(resolve(catalog, path), 'utf8'));
  const sample = /(?:^|[\\/])samples[\\/]([A-Za-z-]+)\.json$/.exec(path);
  if (sample) (samples[folderOf(resolve(catalog, path, '..'))] ??= {})[sample[1]] = JSON.parse(readFileSync(resolve(catalog, path), 'utf8'));
  const name = /(?:^|[\\/])names\.([A-Za-z-]+)\.json$/.exec(path);
  if (name) (names[folderOf(path)] ??= {})[name[1]] = JSON.parse(readFileSync(resolve(catalog, path), 'utf8'));
}
writeFileSync(resolve(catalog, 'about.generated.ts'), `// Generated by scripts/build-packages.mjs from each about.json, samples/ and names file; do not edit.
export const ABOUT: Readonly<Record<string, Readonly<Record<string, unknown>>>> = ${JSON.stringify(about, null, 2)};
export const SAMPLES: Readonly<Record<string, Readonly<Record<string, unknown>>>> = ${JSON.stringify(samples, null, 2)};
export const NAMES: Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, string>>>>>> = ${JSON.stringify(names, null, 2)};
`);

for (const project of ['packages/contracts/tsconfig.json', 'packages/domain/tsconfig.json']) {
  const result = spawnSync(process.execPath, [resolve('node_modules/typescript/bin/tsc'), '-p', project], { stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

// The catalog's prompt files and the composer's rules ship beside the compiled
// domain, where the composer reads them (D11).
cpSync(resolve('packages/domain/src'), resolve('packages/domain/dist'), { recursive: true, filter: source => !/\.ts$/.test(source) });
